// Prints the ambassador-program marks in assets/logos as halftone dot grids
// for HalftoneLogo.
//
//   src/lib/logo-dots.ts   ink coverage per dot cell, one grid per logo
//
// Each dot is sized by how much of its cell the logo covers, like a print
// screen, so detail finer than the grid shows up as smaller dots instead of
// breaking up. Logos are also sized by how much ink they carry, so a thin ring
// and a solid block weigh about the same on the page, and nudged onto the grid
// (like font hinting) so their edges land on cell boundaries where they can.
//
// Run with `pnpm halftone:logos` whenever a logo is added or changes.
import { readdir, writeFile } from "node:fs/promises"
import path from "node:path"
import sharp from "sharp"

const ROOT = path.resolve(import.meta.dirname, "..")
const SRC = path.join(ROOT, "assets/logos")

/** Dots per side. */
const GRID = 16
/** Raster pixels per dot cell when measuring coverage. */
const SUB = 32
const RASTER = GRID * SUB
/**
 * Area of the logo's box, as a share of the square, for a logo whose box is
 * fully inked; sparser logos get a bigger box (see `fit`).
 */
const AREA = 0.5
/** Largest side of a logo's box, as a share of the square. */
const MAX_SIDE = 0.96
/** Hinting tries these scales of the fitted box and shifts of up to half a cell. */
const HINT_SCALES = [0.94, 0.97, 1, 1.03]
const HINT_SHIFTS = [-4, -3, -2, -1, 0, 1, 2, 3, 4].map((i) => (i * SUB) / 8)

const clear = { r: 0, g: 0, b: 0, alpha: 0 }

/** The logo's alpha, trimmed to the mark itself. */
async function trimmed(file) {
  const { data, info } = await sharp(file, { density: 600 })
    .ensureAlpha()
    .trim({ background: clear })
    .extractChannel("alpha")
    .raw()
    .toBuffer({ resolveWithObject: true })
  let ink = 0
  for (const a of data) ink += a / 255
  return { aspect: info.width / info.height, ink: ink / data.length }
}

/**
 * Box size for a logo, as a share of the square. Its area shrinks with the
 * square root of its ink density: halfway between same box for every logo
 * (solid marks look heavy) and same ink for every logo (thin marks blow up).
 */
function fit({ aspect, ink }) {
  const area = AREA / Math.sqrt(ink)
  let w = Math.sqrt(area * aspect)
  let h = w / aspect
  const over = Math.max(w, h) / MAX_SIDE
  if (over > 1) {
    w /= over
    h /= over
  }
  return { w, h }
}

/** Logo alpha resized to w x h pixels. */
async function raster(file, w, h) {
  const { data } = await sharp(file, { density: 600 })
    .ensureAlpha()
    .trim({ background: clear })
    .resize(w, h, { fit: "fill" })
    .extractChannel("alpha")
    .raw()
    .toBuffer({ resolveWithObject: true })
  return data
}

/** Coverage (0-1) per cell with the w x h raster's top-left at (left, top). */
function cells(data, w, h, left, top) {
  const out = new Float64Array(GRID * GRID)
  for (let y = 0; y < h; y++) {
    const row = Math.floor((y + top) / SUB)
    if (row < 0 || row >= GRID) continue
    for (let x = 0; x < w; x++) {
      const col = Math.floor((x + left) / SUB)
      if (col < 0 || col >= GRID) continue
      out[row * GRID + col] += data[y * w + x]
    }
  }
  return out.map((v) => v / (SUB * SUB * 255))
}

/** How many cells are half-covered: the grey that makes a mark look smudged. */
function blur(grid) {
  let sum = 0
  for (const c of grid) sum += c * (1 - c)
  return sum
}

async function coverage(file) {
  const box = fit(await trimmed(file))
  let best = null
  for (const scale of HINT_SCALES) {
    const w = Math.round(box.w * scale * RASTER)
    const h = Math.round(box.h * scale * RASTER)
    if (Math.max(w, h) > RASTER) continue
    const data = await raster(file, w, h)
    for (const dx of HINT_SHIFTS) {
      for (const dy of HINT_SHIFTS) {
        const left = Math.round((RASTER - w) / 2 + dx)
        const top = Math.round((RASTER - h) / 2 + dy)
        if (left < 0 || top < 0 || left + w > RASTER || top + h > RASTER) {
          continue
        }
        const grid = cells(data, w, h, left, top)
        // A slight pull toward the unhinted fit keeps marks from drifting.
        const score = blur(grid) * (1 + Math.abs(scale - 1))
        if (!best || score < best.score) best = { score, grid }
      }
    }
  }
  return Array.from(best.grid, (c) => Math.round(c * 99))
}

const files = (await readdir(SRC)).filter((f) => f.endsWith(".svg")).sort()
const grids = {}
for (const name of files) {
  grids[name.replace(/\.svg$/, "")] = await coverage(path.join(SRC, name))
  console.log(`logo dots: ${name}`)
}

const body = Object.entries(grids)
  .map(([name, data]) => `  ${JSON.stringify(name)}: ${JSON.stringify(data)},`)
  .join("\n")
await writeFile(
  path.join(ROOT, "src/lib/logo-dots.ts"),
  `// Generated by scripts/logo-dots.mjs. Do not edit by hand.
// Ink coverage (0-99) of each cell in a ${GRID}x${GRID} grid, row by row.
export const LOGO_GRID = ${GRID}

export const logoDots = {
${body}
} satisfies Record<string, number[]>

export type LogoName = keyof typeof logoDots
`
)
